#!/usr/bin/env python3
"""Precompute Iron Spire's per-frame channel levels for the Showreel.

    python tools/reel_levels.py

The reel is driven by a frame counter, and filming can run slower than real
time, so it cannot read Chiptune.levels() (the live APU state) and stay in
step with the song. Instead each of the song's four voices is rendered alone
(tools/chiptune_render.c --mute with the other three), the RMS of every
1/30 s window is taken, and the result is written as demo/reel_levels.lua.in:
one level 0..15 per voice per frame, which the reel feeds to
Backgrounds.setLevels.

Chiptune.levels() reports each voice's envelope volume (0..15). A rendered
voice's RMS is proportional to that volume, so one common scale keeps the
voices' balance: the loudest 2% of windows (over all voices) map to 15.
"""
import array
import math
import os
import subprocess
import sys
import tempfile
import wave

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import chiptune  # noqa: E402

SONG = os.path.join(ROOT, "chiptune", "music", "iron_spire.gbm")
OUT = os.path.join(ROOT, "demo", "reel_levels.lua.in")
VOICES = 4
FPS = 30
SECONDS = 44          # 32 bars are 42.9 s, plus the hold at the end
RATE = 44100
LINE = 60             # frames per line of the generated string


def voice_rms(exe, voice, tmp):
    wav = os.path.join(tmp, "v%d.wav" % voice)
    mask = ((1 << VOICES) - 1) & ~(1 << voice)
    subprocess.run([exe, SONG, wav, "--seconds", str(SECONDS), "--mono", "--rate", str(RATE),
                    "--mute", str(mask)], check=True, stdout=subprocess.DEVNULL)
    with wave.open(wav) as w:
        assert w.getnchannels() == 1 and w.getframerate() == RATE
        pcm = array.array("h")
        pcm.frombytes(w.readframes(w.getnframes()))
    win = RATE // FPS
    out = []
    for k in range(SECONDS * FPS):
        chunk = pcm[k * win:(k + 1) * win]
        out.append(math.sqrt(sum(s * s for s in chunk) / len(chunk)) if chunk else 0.0)
    return out


def main():
    exe = chiptune.renderer()
    with tempfile.TemporaryDirectory() as tmp:
        rms = [voice_rms(exe, v, tmp) for v in range(VOICES)]
    flat = sorted(x for r in rms for x in r if x > 0)
    top = flat[int(len(flat) * 0.98)] if flat else 1.0
    frames = SECONDS * FPS
    rows = []
    for k in range(frames):
        rows.append("".join("%x" % min(15, int(round(15 * rms[v][k] / top))) for v in range(VOICES)))
    for v in range(VOICES):
        print("voice %d: max %.0f, mean level %.1f" % (
            v, max(rms[v]), sum(min(15, 15 * x / top) for x in rms[v]) / frames))
    lines = ["".join(rows[i:i + LINE]) for i in range(0, frames, LINE)]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("-- Generated by tools/reel_levels.py: Iron Spire's channel levels, one hex digit\n")
        f.write("-- (0..15) per voice per frame at %d fps, %d voices a frame. Do not edit.\n" % (FPS, VOICES))
        f.write("ReelLevels = {\n    voices = %d, frames = %d,\n    data = {\n" % (VOICES, frames))
        for line in lines:
            f.write('        "%s",\n' % line)
        f.write("    },\n}\n")
    print("wrote", OUT, frames, "frames")


if __name__ == "__main__":
    main()

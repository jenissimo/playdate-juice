/* PCM8 interpolation, loop addressing, root pitch, bank validation and the
   shared driver/queue. Fixtures are generated by tools/chiptune.py test. */
#define _CRT_SECURE_NO_WARNINGS
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "../../chiptune/chip.h"
#include "../../chiptune/bank_codec.h"

static int checks, fails;
#define CHECK(c, ...) do { checks++; if (!(c)) { fails++; printf("FAIL: " __VA_ARGS__); printf("\n"); } } while (0)
static int16_t L[4096], R[4096], other[4096];
static uint32_t u32(const uint8_t *p) { return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24); }

static uint8_t *read_file(const char *path, uint32_t *size)
{
    FILE *f = fopen(path, "rb");
    uint8_t *b;
    if (!f) exit(2);
    fseek(f, 0, SEEK_END); *size = (uint32_t)ftell(f); rewind(f);
    b = malloc(*size);
    if (!b || fread(b, 1, *size, f) != *size) exit(2);
    fclose(f); return b;
}

static void synth_tests(void)
{
    static const uint8_t data[4] = {128, 192, 0, 64};
    Vox x, y;
    float pos;
    int i, voiced = 0;
    vox_init(&x, 22050);
    vox_sample8(&x, 0, data, 4, 11025, 523251, 0, 0);
    vox_trigger(&x, 0, OSC_SAMPLE, 48 * 256, 0xF0); /* C5, half a source sample per output */
    CHECK(x.v[0].inc > 0.499f && x.v[0].inc < 0.501f, "source rate at its root");
    vox_render(&x, L, R, 16);
    CHECK(L[0] < L[1] && L[1] < L[2] && abs(2 * L[1] - L[0] - L[2]) < 4, "PCM8 uses signed values and interpolation");
    CHECK(!x.v[0].on && L[12] == 0, "a one-shot ends and silences the voice");
    vox_init(&x, 22050);
    vox_sample8(&x, 0, data, 4, 11025, 523251, 1, 4);
    vox_trigger(&x, 0, OSC_SAMPLE, 48 * 256, 0xF0);
    vox_render(&x, L, R, 8);
    CHECK(abs(L[7]) < 4, "interpolation at loop end reads loop start, not past the sample");
    vox_render(&x, L, R, 4096);
    CHECK(x.v[0].on && x.v[0].smp_pos >= 1.0f && x.v[0].smp_pos < 4.0f, "sustain survives many wraps");
    for (i = 0; i < 4096; i++) if (L[i]) voiced++;
    CHECK(voiced > 2000, "sustain keeps producing audio");
    vox_trigger(&x, 0, OSC_SAMPLE, 60 * 256, 0xF0);
    CHECK(x.v[0].smp_pos == 0.0f && x.v[0].inc > 0.999f && x.v[0].inc < 1.001f, "retrigger restarts; an octave doubles rate");
    vox_sample8(&x, 0, data, 4, 192000, 32703, 1, 4);
    vox_trigger(&x, 0, OSC_SAMPLE, 72 * 256, 0xF0);
    vox_render(&x, L, R, 100);
    CHECK(x.v[0].on && x.v[0].smp_pos >= 1.0f && x.v[0].smp_pos < 4.0f, "a high note can traverse a loop several times per output sample");
    vox_init(&x, 44100);
    vox_sample8(&x, 0, data, 4, 16384, 55000, 1, 4);
    vox_trigger(&x, 0, OSC_SAMPLE, 9 * 256, 0xF0); /* A1, below the DMG's tonal floor */
    CHECK(x.v[0].inc > 0.3714f && x.v[0].inc < 0.3716f, "A1 bass plays at 55 Hz, not the DMG floor");
    y = x;
    vox_render(&x, L, R, 4096);
    for (i = 0; i < 4096; i += 16) vox_render(&y, other + i, NULL, 16);
    CHECK(!memcmp(L, other, sizeof L), "loop output is independent of callback partitioning");
    pos = y.v[0].smp_pos;
    vox_pitch(&y, 0, 21 * 256);
    CHECK(y.v[0].smp_pos == pos && y.v[0].inc > 0.7428f && y.v[0].inc < 0.7432f, "pitch updates preserve playback position");
    vox_off(&y, 0);
    vox_render(&y, other, NULL, 16);
    CHECK(other[0] == 0 && !y.v[0].on, "note off stops a sustain");
    vox_sample(&y, 0, data, 8);
    CHECK(y.v[0].smp_bits == 4 && !y.v[0].smp_loop_end, "legacy samples clear PCM8 metadata");
    vox_init(&x, 44100);
    vox_sample8(&x, 0, data, 4, 16384, 55000, 1, 4);
    vox_articulation(&x, 0, 30, 256);
    vox_trigger(&x, 0, OSC_SAMPLE, 9 * 256, 0xF0);
    vox_render(&x, L, R, 100);
    vox_note_tail(&x, 0);
    vox_trigger(&x, 0, OSC_SAMPLE, 21 * 256, 0xF0);
    CHECK(x.tail[0].on && x.tail[0].releasing && x.v[0].smp_pos == 0, "retrigger keeps a bounded release overlap");
    vox_release(&x, 0);
    vox_render(&x, L, R, 441);
    CHECK(x.v[0].on && x.v[0].release_gain > 0.6f && x.v[0].release_gain < 0.7f, "note-off fades over the instrument's 30 ms");
    vox_render(&x, L, R, 2000);
    CHECK(!x.v[0].on && !x.tail[0].on, "release and overlap both terminate");
    vox_init(&x, 44100); vox_output(&x, 2048);
    for (i = 0; i < 8; i++) vox_trigger(&x, i, OSC_PULSE, 1750, 0xF0);
    vox_render(&x, L, R, 4096);
    for (i = 0; i < 4096; i++) if (abs(L[i]) > 29203 || abs(R[i]) > 29203) break;
    CHECK(i == 4096 && x.comp_power > 0, "mastered output limits peaks to -1 dBFS without invalid samples");
}

static void driver_tests(const char *song_path, const char *bank_path, const char *sfx_path)
{
    uint32_t sn, bn, fn;
    uint8_t *song = read_file(song_path, &sn), *bank = read_file(bank_path, &bn), *sfx = read_file(sfx_path, &fn);
    Chip c;
    int i;
    CHECK(!gbm_check(song, sn) && !gbm_sample_bank_check(bank, bn), "v3 song and shared bank validate");
    CHECK(bn > 65535 && u32(bank + 36) > 65535, "32-bit offsets address samples beyond 64 KiB");
    CHECK(gbm_sample_bank_match(song, bank) && !gbm_sample_bank_match(song, NULL), "v3 requires its bank");
    bank[bn - 1] ^= 1;
    CHECK(gbm_sample_bank_check(bank, bn) != 0, "a damaged PCM payload is rejected");
    bank[bn - 1] ^= 1;
    bank[8] ^= 1;
    CHECK(!gbm_sample_bank_match(song, bank), "wrong bank identity is rejected");
    bank[8] ^= 1;
    CHECK(gbm_sample_bank_check(bank, 40) != 0, "a truncated bank is rejected");
    bank[28] = 255; /* loop start >= exclusive end */
    CHECK(gbm_sample_bank_check(bank, bn) != 0, "invalid loop bounds are rejected");
    bank[28] = 0;
    chip_init(&c, 44100);
    CHECK(!chip_post(&c, CHIP_PLAY, 0, 0, song), "missing bank is rejected before entering the queue");
    CHECK(chip_post_bank(&c, CHIP_PLAY, 0, 0, song, bank), "queue accepts an atomic song/bank pair");
    chip_render(&c, L, R, 2048);
    CHECK(c.gbm.playing && c.gbm.v2 && c.gbm.nv == 2 && c.gbm.sync == 42, "shared sequencer starts PCM music and sync markers");
    CHECK(c.vox.v[0].smp_bits == 8 && c.vox.v[0].smp == bank + u32(bank + 12), "voice uses the external PCM bank without a copy");
    CHECK(c.vox.v[0].inc > 0.3714f && c.vox.v[0].inc < 0.3716f, "driver converts A1 into PCM pitch");
    chip_post(&c, CHIP_MUTE, 1, 0, NULL);
    chip_render(&c, L, R, 1024);
    CHECK(!c.vox.v[0].on && c.gbm.ch[0].block, "mute blocks a PCM layer while time advances");
    chip_post(&c, CHIP_MUTE, 0, 0, NULL);
    chip_render(&c, L, R, 1024);
    CHECK(c.vox.v[0].on, "unmute retriggers the held layer");
    chip_post(&c, CHIP_PAUSE, 1, 0, NULL);
    chip_render(&c, L, R, 256);
    CHECK(c.gbm.paused && !c.vox.v[0].on, "pause silences the loop");
    chip_post(&c, CHIP_PAUSE, 0, 0, NULL);
    chip_render(&c, L, R, 512);
    CHECK(c.vox.v[0].on, "resume restores PCM music");
    /* A legacy 4-bit sample borrows the PCM8 bass's voice and returns it. */
    CHECK(!gbm_check(sfx, fn), "legacy SFX fixture validates");
    chip_post(&c, CHIP_SFX_BANK, 0, 0, sfx);
    chip_post(&c, CHIP_DUCK, 4, 1, NULL);
    chip_post(&c, CHIP_SFX, 0, 0, NULL);
    chip_render(&c, L, R, 1024);
    CHECK(c.vox.v[0].smp_bits == 4 && c.gbm.owner[0] != 255, "legacy sampled SFX can borrow a PCM8 voice");
    for (i = 0; i < 30; i++) chip_render(&c, L, R, 1024);
    CHECK(c.gbm.owner[0] == 255 && c.vox.v[0].smp_bits == 8 && c.vox.v[0].on, "SFX release restores the studio sample and its loop");
    chip_post_bank(&c, CHIP_SFX_BANK, 0, 0, song, bank);
    chip_post(&c, CHIP_SFX, 0, 0, NULL);
    chip_render(&c, L, R, 1024);
    CHECK(c.vox.v[7].smp_bits == 8 && c.vox.v[7].smp == bank + u32(bank + 36), "PCM8 SFX read a high-offset sample on a spare voice");
    chip_post(&c, CHIP_STOP, 0, 0, NULL);
    chip_post(&c, CHIP_SFX_STOP, 0, 0, NULL);
    chip_render(&c, L, R, 256);
    CHECK(!c.gbm.playing && !vox_active(&c.vox), "stop silences every PCM layer");
    free(song); free(bank); free(sfx);
}

static void packed_tests(const char *raw_path, const char *packed_path, const char *extended_path)
{
    uint32_t rn, pn, en;
    uint8_t *raw = read_file(raw_path, &rn), *packed = read_file(packed_path, &pn), *ext = read_file(extended_path, &en);
    void *workspace = malloc(bank_workspace_size());
    uint8_t *out = malloc(rn);
    Chip c;
    int i;
    CHECK(pn < rn && bank_raw_size(packed, pn) == rn, "lossless bank wrapper reports its decoded size");
    CHECK(!bank_unpack(packed, pn, out, rn, workspace) && !memcmp(raw, out, rn), "Python encoder and C decoder reproduce the complete bank byte for byte");
    CHECK(bank_unpack(packed, pn / 2, out, rn, workspace) != 0, "truncated compressed banks are rejected");
    packed[8] ^= 1;
    CHECK(bank_unpack(packed, pn, out, rn, workspace) != 0, "a damaged compressed identity is rejected");
    packed[8] ^= 1;
    CHECK(!gbm_check(ext, en) && gbm_sample_bank_match(ext, raw), "extended v3 header matches the same bank");
    chip_init(&c, 44100);
    chip_post_bank(&c, CHIP_PLAY, 0, 0, ext, raw);
    for (i = 0; i < 10; i++) chip_render(&c, L, R, 4096);
    chip_render(&c, L, R, 3140);
    CHECK(c.gbm.frame_cycles == 74898 && c.ticks >= 56 && c.ticks <= 57, "140 BPM uses a 56 Hz musical clock");
    CHECK(c.vox.v[0].release_ms == 30 && c.vox.output_gain == 1.0f, "extended instruments configure release and mastering");
    free(raw); free(packed); free(ext); free(out); free(workspace);
}

int main(int argc, char **argv)
{
    synth_tests();
    if (argc != 6) return 2;
    driver_tests(argv[1], argv[2], argv[3]);
    packed_tests(argv[2], argv[4], argv[5]);
    printf("v3: %d checks, %d failures\n", checks, fails);
    return fails ? 1 : 0;
}
